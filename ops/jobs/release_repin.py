"""Same-host release re-pin of a stopped remote run (remote MIG migration, user directive 2026-11-11 ~19:00).

A stopped run keeps its job id, arguments, fingerprint, data identity, image and run directory. Its target must have
campaign acceptance. The original identical-scope variant path remains available. With --allowed-differences, the
target is the exact approved MIG head: every execution-scope difference must match either the approved full MIG patch
or byte-bound per-file independent review evidence. A plan is read-only and reports pending acceptance/approval;
apply appends one release_repinned event and never launches, stops or deletes anything.

Evidence JSON: {from_commit, to_commit, scopes: {<trainer script>: {scripts: [trainer, remote entry],
               differences: {<file>: {change: {before_sha256, after_sha256}, justification, reviewer_verdict}}}}}.
Third-party changes use {before, after} rather than byte hashes. Every event records the evidence path/hash and full
actual differences, including operational files. An uncovered difference refuses; evidence is not a release acceptance.
The coordinator's APPROVED_PATCH record additionally binds execution_patch_sha256 (full binary git diff) for this path;
patch_sha256 still binds mig_variant.mig_patch for the legacy variant path. Neither approval is generated by this tool.

USE ONLY AFTER THE USER'S EXPLICIT RESUME AUTHORIZATION (the event records it).

    python -I ops/jobs/release_repin.py plan  --to-commit C --to-image I <job id>
    python -I ops/jobs/release_repin.py apply --to-commit C --to-image I --authorization TEXT <job id>
"""

from __future__ import annotations

import argparse
import contextlib
import fcntl
import functools
import hashlib
import json
import os
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from ops.jobs.migration import commit_reader, import_closure  # noqa: E402

# Files allowed to differ between the pinned and the destination release: the GPU allowlist and its consumers inside
# the container (recorded in the event, not compared). Everything else in the scripts' import closure, the task / model
# configuration trees and the environment pins must be byte-identical.
REPIN_OPERATIONAL = frozenset({"ops/resources/gpu_guard.py", "ops/resources/mig_inventory.py", "mujoco_mig_setup.py",
                               "configs/hosts/remote.yaml", "configs/hosts/remote-mig.yaml",
                               # runtime provenance: accepts exactly the recorded re-pin transition (Codex #6)
                               "ops/jobs/run_identity.py", "ops/containers/verification.py"})
REPIN_CONFIG_SCOPE = ("configs/realworld/", "configs/metaworld/", "configs/rl/", "configs/baselines/")
REPIN_ENVIRONMENT = ("uv.lock", "pyproject.toml")
STOPPED = {"crashed", "pending", "failed"}
# the reviewed MIG patch range, recorded by the coordinator after review ({"mig_base", "mig_head", "patch_sha256",
# "approved_by"}); release_repin accepts only operational differences produced by exactly this patch (review 3, 7)
APPROVED_PATCH = "runs/setup/remote-mig-approved-patch.json"


class RepinError(RuntimeError):
    pass


def scope_comparison(scripts, before_read, before_listed, after_read, after_listed, before_third_party=None,
                     after_third_party=None) -> dict:
    """{"identical", "differences", "operational_differences", "files"} for two release trees given as readers; the
    third-party pins (submodule commits, .gitmodules, patches: ops.provenance.upstreams.commit_identity) must be equal
    too."""
    paths = import_closure(scripts, before_read) | import_closure(scripts, after_read)
    paths |= {p for p in list(before_listed) + list(after_listed) if p.startswith(REPIN_CONFIG_SCOPE)}
    paths |= set(REPIN_ENVIRONMENT) | set(REPIN_OPERATIONAL)
    files, differences, operational, records = {}, [], [], {}
    for relative in sorted(paths):
        before, after = before_read(relative), after_read(relative)
        if before != after:
            records[relative] = {"before_sha256": hashlib.sha256(before).hexdigest() if before is not None else None,
                                 "after_sha256": hashlib.sha256(after).hexdigest() if after is not None else None}
        if relative in REPIN_OPERATIONAL:
            operational += [relative] if before != after else []
            continue
        if before != after:
            differences.append(relative)
        if after is not None:
            files[relative] = hashlib.sha256(after).hexdigest()
    before_tp, after_tp = before_third_party or {}, after_third_party or {}
    differences += [f"third_party:{key}" for key in sorted(set(before_tp) | set(after_tp))
                    if before_tp.get(key) != after_tp.get(key)]
    for key in sorted(set(before_tp) | set(after_tp)):
        if before_tp.get(key) != after_tp.get(key):
            records[f"third_party:{key}"] = {"before": before_tp.get(key), "after": after_tp.get(key)}
    return {"difference_records": records, "identical": not differences, "differences": differences,
            "operational_differences": operational,
            "files": files, "third_party": after_tp}


def check_state(job_id: str, current: dict, to_commit: str, to_image: str) -> None:
    """The run must be a stopped remote run pinned to another release (refuses active / unknown / never launched), on
    the SAME image (identical sources do not prove an identical environment), and never previously re-pinned."""
    if current.get("image_digest") != to_image:
        raise RepinError(f"{job_id}: image change {current.get('image_digest')} -> {to_image} refused (same-science "
                         "variants keep the original image)")
    earlier = current.get("repinned_from")
    if earlier:  # Codex review 3 (13): one re-pin per run; a chain could outrun the provenance recorded on disk
        raise RepinError(f"{job_id}: already re-pinned once (from {str(earlier.get('commit'))[:7]}); a further move needs "
                         "the run's provenance.json release_history verified by hand")
    if current.get("host") != "remote" or not current.get("commit") or not current.get("image_digest"):
        raise RepinError(f"{job_id}: not a launched remote run")
    if current.get("status") not in STOPPED or current.get("unknown"):
        raise RepinError(f"{job_id}: status {current.get('status')} (unknown={current.get('unknown')}); only a "
                         "stopped run whose container exit is recorded can be re-pinned")
    if current["commit"] == to_commit:
        raise RepinError(f"{job_id}: already on {to_commit[:7]}")


def check_operational(scope: dict, expected: dict[str, bytes | None], after_read) -> None:
    """Every operational (allowlist-related) difference must be exactly the reviewed MIG patch applied to the source
    release (mig_variant.expected_operational); configuration files under configs/hosts are data and compared by the
    allowlist validation instead."""
    for name in scope["operational_differences"]:
        if name.startswith("configs/hosts/"):
            continue
        if name not in expected or after_read(name) != expected[name]:
            raise RepinError(f"operational file {name} differs from the reviewed MIG patch of the source release")


def reviewed_scope(scope: dict, evidence_path: Path, from_commit: str, to_commit: str, scripts,
                   mig_base_read, mig_head_read) -> dict:
    """Cover every difference with the exact approved MIG delta or byte-bound independent review.

    A filename alone cannot waive a later edit: evidence binds source/target commits, scripts and both file hashes.
    Historical differences in a MIG-touched file still require review when its source is not the MIG base's bytes.
    """
    payload = evidence_path.read_bytes()
    evidence = json.loads(payload)
    if evidence.get("from_commit") != from_commit or evidence.get("to_commit") != to_commit:
        raise RepinError("allowed-differences release/script identity mismatch")
    evidence_scope = evidence.get("scopes", {}).get(scripts[0], evidence)
    if sorted(evidence_scope.get("scripts", [])) != sorted(scripts):
        raise RepinError("allowed-differences script scope mismatch")
    allowed = evidence_scope.get("differences")
    if not isinstance(allowed, dict):
        raise RepinError("allowed-differences must contain a per-file differences object")
    uncovered, coverage = [], {}
    for name, record in scope["difference_records"].items():
        before, after = mig_base_read(name), mig_head_read(name)
        mig_record = {"before_sha256": hashlib.sha256(before).hexdigest() if before is not None else None,
                      "after_sha256": hashlib.sha256(after).hexdigest() if after is not None else None}
        if not name.startswith("third_party:") and before != after and record == mig_record:
            coverage[name] = "approved_mig_patch"
            continue
        item = allowed.get(name, {})
        if (not isinstance(item, dict) or item.get("change") != record
                or not isinstance(item.get("justification"), str) or not item["justification"].strip()
                or not isinstance(item.get("reviewer_verdict"), str) or not item["reviewer_verdict"].strip()):
            uncovered.append(name)
        else:
            coverage[name] = "reviewer_evidence"
    if uncovered:
        raise RepinError(f"execution scope differs without review coverage: {uncovered}")
    if set(allowed) - set(scope["difference_records"]):
        raise RepinError("allowed-differences contains files outside the actual difference list")
    return {**scope, "reviewed_equivalent": True, "coverage": coverage,
            "allowed_differences": {"path": str(evidence_path.resolve()),
                                    "sha256": hashlib.sha256(payload).hexdigest()}}


def approved_patch(root: Path, base: str, head: str, path: Path, *, full_scope=False) -> dict:
    from ops.jobs.mig_variant import git, mig_patch

    execution_digest = hashlib.sha256(git(root, "diff", "--binary", "--full-index", base, head)).hexdigest()
    digest = hashlib.sha256(mig_patch(root, base, head)).hexdigest()
    approved = json.loads(path.read_text()) if path.is_file() else {}
    valid = ((approved.get("mig_base"), approved.get("mig_head"), approved.get("patch_sha256")) == (base, head, digest)
             and bool(str(approved.get("approved_by", "")).strip()))
    if full_scope:
        valid = valid and approved.get("execution_patch_sha256") == execution_digest
    return {"base": base, "head": head, "sha256": digest, "execution_patch_sha256": execution_digest, "approved": valid,
            "record": str(path.resolve())}


def repin_event(job_id: str, current: dict, to_commit: str, to_image: str, scope: dict, scripts, authorization: str) -> dict:
    if not scope["identical"] and not scope.get("reviewed_equivalent"):
        raise RepinError(f"{job_id}: execution scope differs: {scope['differences'][:8]}")
    if not authorization.strip():
        raise RepinError("the user's explicit resume authorization must be recorded")
    return {"event": "release_repinned", "id": job_id, "host": "remote", "attempt": current.get("attempt"),
            "from_commit": current["commit"], "from_image_digest": current["image_digest"],
            "commit": to_commit, "image_digest": to_image, "sources_identical": True,
            "execution_scope_identical": not scope.get("difference_records", scope["differences"]),
            "operational_differences": scope["operational_differences"], "scripts": list(scripts),
            "scope_sha256": hashlib.sha256(json.dumps(scope["files"], sort_keys=True).encode()).hexdigest(),
            "authorization": authorization.strip(),
            **({"allowed_differences": scope["allowed_differences"], "differences": scope["difference_records"],
                "difference_coverage": scope["coverage"], "reviewed_equivalent": True}
               if scope.get("reviewed_equivalent") else {})}


def main(argv=None) -> int:
    from ops.jobs import scheduler as jobs  # noqa: PLC0415

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("plan", "apply"))
    parser.add_argument("--to-commit", required=True)
    parser.add_argument("--to-image", required=True)
    parser.add_argument("--authorization", default="")
    parser.add_argument("--mig-base", required=True,
                        help="the main commit the rebased reviewed MIG patch is based on (c7d0538)")
    parser.add_argument("--mig-head", required=True, help="the reviewed MIG head whose patch the variant carries")
    parser.add_argument("--allowed-differences", type=Path, help="byte-bound per-file independent review evidence")
    parser.add_argument("--queue", type=Path, default=jobs.QUEUE)
    parser.add_argument("--registry", type=Path, default=jobs.REGISTRY)
    parser.add_argument("--approved-patch", type=Path, default=REPO / APPROVED_PATCH)
    parser.add_argument("--acceptance-manifest", type=Path, help="accepted target release manifest (required for apply)")
    parser.add_argument("job_id")
    args = parser.parse_args(argv)
    from ops.jobs.mig_variant import expected_operational, git
    from ops.provenance.upstreams import commit_identity

    for key in ("to_commit", "mig_base", "mig_head"):
        setattr(args, key, git(REPO, "rev-parse", f"{getattr(args, key)}^{{commit}}").decode().strip())
    queue = {job["id"]: job for job in jobs.load_queue(args.queue)["jobs"]}
    if args.job_id not in queue:
        raise RepinError(f"unknown queued job {args.job_id}")
    job = queue[args.job_id]
    scripts = [job["script"], "scripts/remote/entry.py"]
    # plan is strictly read-only, including no registry lock-file creation.
    lock_context = (args.registry.with_suffix(".lock").open("a") if args.command == "apply"
                    else contextlib.nullcontext(None))
    with lock_context as lock:
        if lock is not None:
            fcntl.flock(lock, fcntl.LOCK_EX)
        current = jobs.read_registry(args.registry).get(args.job_id, {})
        check_state(args.job_id, current, args.to_commit, args.to_image)
        if current.get("job_sha256") != jobs.job_fingerprint(job):
            raise RepinError(f"{args.job_id}: queue fingerprint differs from the launched run")
        before_read, before_listed = commit_reader(REPO, current["commit"])
        after_read, after_listed = commit_reader(REPO, args.to_commit)
        before_read, after_read = functools.cache(before_read), functools.cache(after_read)
        scope = scope_comparison(scripts, before_read, before_listed, after_read, after_listed,
                                 commit_identity(REPO, current["commit"]), commit_identity(REPO, args.to_commit))
        patch = approved_patch(REPO, args.mig_base, args.mig_head, args.approved_patch,
                               full_scope=bool(args.allowed_differences))
        blockers = []
        if args.allowed_differences:
            if args.to_commit != args.mig_head:
                raise RepinError("reviewed re-pin target must be the exact approved MIG head")
            base_read, _ = commit_reader(REPO, args.mig_base)
            try:
                scope = reviewed_scope(scope, args.allowed_differences, current["commit"], args.to_commit, scripts,
                                       functools.cache(base_read), after_read)
            except RepinError as exc:
                if args.command != "plan":
                    raise
                blockers.append(str(exc))
        else:
            if not patch["approved"]:
                raise RepinError(f"MIG patch is not approved in {args.approved_patch}")
            check_operational(scope, expected_operational(REPO, current["commit"], args.mig_base, args.mig_head), after_read)
        if not patch["approved"]:
            blockers.append("MIG patch approval pending")
        acceptance = None
        if args.acceptance_manifest:
            from ops.jobs.remote_backend import acceptance_manifest
            acceptance = acceptance_manifest({"commit": args.to_commit, "image_digest": args.to_image,
                                               "evidence_manifest": str(args.acceptance_manifest)}, REPO)
            if current.get("data_identity") != acceptance["data_identity"]:
                raise RepinError("target acceptance data identity differs from the launched run")
        else:
            blockers.append("target release acceptance pending")
        covered = scope.get("reviewed_equivalent", False) if args.allowed_differences else scope["identical"]
        if args.command == "plan":
            print(json.dumps({"id": args.job_id, "from_commit": current["commit"], "to_commit": args.to_commit,
                              "image_digest": args.to_image, "scope_covered": covered,
                              "differences": scope["difference_records"], "coverage": scope.get("coverage", {}),
                              "allowed_differences": scope.get("allowed_differences"), "mig_patch": patch,
                              "apply_blockers": blockers}, indent=1))
            return 0 if not blockers and covered else 3
        if blockers:
            raise RepinError("; ".join(blockers))
        event = repin_event(args.job_id, current, args.to_commit, args.to_image, scope, scripts, args.authorization)
        event["job_sha256"] = current["job_sha256"]
        event["mig_patch"] = patch
        event["acceptance"] = {"path": str(args.acceptance_manifest), "sha256": acceptance["manifest_sha256"],
                               "data_identity": acceptance["data_identity"]}
        with args.registry.open("a") as stream:
            stream.write(json.dumps({**event, "time": time.time()}) + "\n")
            stream.flush()
            os.fsync(stream.fileno())
    print(json.dumps(event, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
