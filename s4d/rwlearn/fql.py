"""Flow Q-Learning (FQL), a faithful PyTorch port of the official JAX agent.

Reference: S. Park, Q. Li, S. Levine, "Flow Q-Learning", ICML 2025; code github.com/seohongpark/fql (MIT, (c) 2025 FQL
Authors) at commit ``e8cd16eb490332924dfa2492097219f181765933`` (``agents/fql.py``, ``utils/networks.py``,
``utils/flax_utils.py``). Why a port and not the JAX code itself: docs/realworld_fql.md ("Implementation choice").

What is reproduced exactly (checked against fixtures generated by the official code, tests/test_rwlearn_fql.py):

* networks: ``MLP`` (Dense with variance_scaling(1, fan_avg, uniform) kernels = Xavier-uniform, zero biases, tanh-GELU
  (``flax.linen.gelu`` default ``approximate=True``), LayerNorm with epsilon 1e-6 after every hidden activation when
  enabled, no activation on the output); ``Value`` = 2-member ensemble of MLPs on concat(obs, action) -> (2, B);
  ``ActorVectorField`` = MLP on concat(obs, action[, time]);
* losses: critic MSE to ``r + gamma * mask * agg(target Q(s', clip(pi(s'))))`` with ``agg`` = mean (``q_agg``);
  actor = BC flow-matching loss + alpha * distillation of the 10-step Euler flow into the one-step policy - Q (mean over
  the ensemble, optionally normalised); gradients exactly where the official code lets them flow (the target critic,
  the Euler flow targets, the next actions and the critic inside the actor's Q term are all stop-gradient);
* one Adam step (optax.adam defaults: b1 0.9, b2 0.999, eps 1e-8) on the summed loss, then the Polyak target update
  with the PRE-update online critic (the official ``target_update`` reads ``self.network``, i.e. the old parameters);
* the target critic starts as a copy of the critic.

Randomness: JAX and torch draw different numbers, so every draw goes through ``Noise`` (the five Gaussian/uniform
arrays one update consumes, in the official order). Training draws them from a seeded ``torch.Generator``; the
equivalence tests inject the official draws.

The optional ``encoder`` (official: one encoder instance per network, ``config['encoder']``) is a factory returning an
``nn.Module`` that maps an observation (tensor or dict) to a flat vector; each of critic / BC flow / one-step flow gets
its own instance, the target critic a copy of the critic's (as the official ModuleDict does). The official
``impala_small`` pixel encoder is ported in ``s4d.rwlearn.pixel`` (equivalence with an official pixel agent:
tests/test_rwlearn_pixel.py).
"""

from __future__ import annotations

import copy
from collections.abc import Callable
from dataclasses import dataclass, field

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.func import functional_call

FQL_COMMIT = "e8cd16eb490332924dfa2492097219f181765933"
FLAX_LAYERNORM_EPS = 1e-6


def official_config(**overrides) -> dict:
    """``agents/fql.py::get_config`` defaults (ob_dims/action_dim are set from data)."""
    cfg = dict(
        agent_name="fql",
        lr=3e-4,
        batch_size=256,
        actor_hidden_dims=(512, 512, 512, 512),
        value_hidden_dims=(512, 512, 512, 512),
        layer_norm=True,
        actor_layer_norm=False,
        discount=0.99,
        tau=0.005,
        q_agg="mean",
        alpha=10.0,
        flow_steps=10,
        normalize_q_loss=False,
        encoder=None,
    )
    unknown = set(overrides) - set(cfg)
    if unknown:
        raise KeyError(f"unknown FQL config keys {sorted(unknown)}")
    cfg.update(overrides)
    if cfg["q_agg"] not in ("mean", "min"):
        raise ValueError(f"q_agg must be 'mean' or 'min', got {cfg['q_agg']!r}")
    return cfg


def gelu(x: torch.Tensor) -> torch.Tensor:
    return F.gelu(x, approximate="tanh")  # flax.linen.gelu(approximate=True)


class MLP(nn.Module):
    """``utils/networks.py::MLP``."""

    def __init__(self, in_dim: int, hidden_dims, activate_final: bool = False, layer_norm: bool = False):
        super().__init__()
        dims = [int(in_dim), *[int(h) for h in hidden_dims]]
        self.activate_final, self.layer_norm = bool(activate_final), bool(layer_norm)
        self.linears = nn.ModuleList(nn.Linear(a, b) for a, b in zip(dims[:-1], dims[1:]))
        n = len(self.linears)
        self.norms = nn.ModuleList(
            nn.LayerNorm(dims[i + 1], eps=FLAX_LAYERNORM_EPS) if layer_norm and (i + 1 < n or activate_final)
            else nn.Identity() for i in range(n))
        for lin in self.linears:
            nn.init.xavier_uniform_(lin.weight)  # variance_scaling(1.0, 'fan_avg', 'uniform')
            nn.init.zeros_(lin.bias)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        n = len(self.linears)
        for i, (lin, norm) in enumerate(zip(self.linears, self.norms)):
            x = lin(x)
            if i + 1 < n or self.activate_final:
                x = gelu(x)
                if self.layer_norm:
                    x = norm(x)
        return x


class Value(nn.Module):
    """``utils/networks.py::Value`` with ``num_ensembles`` independent MLPs (official ``ensemblize`` / vmap)."""

    def __init__(self, in_dim: int, hidden_dims, layer_norm: bool = True, num_ensembles: int = 2, encoder=None):
        super().__init__()
        self.encoder = encoder
        self.members = nn.ModuleList(MLP(in_dim, (*hidden_dims, 1), activate_final=False, layer_norm=layer_norm)
                                     for _ in range(num_ensembles))

    def forward(self, observations, actions: torch.Tensor) -> torch.Tensor:
        obs = self.encoder(observations) if self.encoder is not None else observations
        inputs = torch.cat([obs, actions], dim=-1)
        return torch.stack([m(inputs).squeeze(-1) for m in self.members], dim=0)  # (E, B)


class ActorVectorField(nn.Module):
    """``utils/networks.py::ActorVectorField``."""

    def __init__(self, in_dim: int, hidden_dims, action_dim: int, layer_norm: bool = False, encoder=None):
        super().__init__()
        self.encoder = encoder
        self.mlp = MLP(in_dim, (*hidden_dims, action_dim), activate_final=False, layer_norm=layer_norm)

    def encode(self, observations):
        return self.encoder(observations) if self.encoder is not None else observations

    def forward(self, observations, actions: torch.Tensor, times: torch.Tensor | None = None,
                is_encoded: bool = False) -> torch.Tensor:
        obs = observations if is_encoded else self.encode(observations)
        parts = [obs, actions] if times is None else [obs, actions, times]
        return self.mlp(torch.cat(parts, dim=-1))


@dataclass
class Noise:
    """The random draws of one official ``update``, in its order: ``next_actions`` (critic: one-step policy noise at
    s'), ``x0`` and ``t`` (actor: flow-matching source and time), ``distill`` (actor: shared noise of the Euler flow
    target and the one-step policy), ``mse`` (actor: logging-only policy sample)."""

    next_actions: torch.Tensor
    x0: torch.Tensor
    t: torch.Tensor
    distill: torch.Tensor
    mse: torch.Tensor

    @classmethod
    def draw(cls, batch_size: int, action_dim: int, generator: torch.Generator, device) -> Noise:
        def normal():
            return torch.randn(batch_size, action_dim, generator=generator).to(device)

        return cls(next_actions=normal(), x0=normal(), t=torch.rand(batch_size, 1, generator=generator).to(device),
                   distill=normal(), mse=normal())


@dataclass
class FQLAgent:
    """Official ``FQLAgent`` (critic, target_critic, actor_bc_flow, actor_onestep_flow; one Adam optimiser)."""

    config: dict
    obs_dim: int
    action_dim: int
    device: torch.device
    critic: Value = field(init=False)
    target_critic: Value = field(init=False)
    actor_bc_flow: ActorVectorField = field(init=False)
    actor_onestep_flow: ActorVectorField = field(init=False)

    @classmethod
    def create(cls, seed: int, obs_dim: int, action_dim: int, config: dict, *, device="cpu",
               encoder: Callable[[], nn.Module] | None = None) -> FQLAgent:
        """``obs_dim``: the MLP input width of an (encoded) observation. ``encoder``: optional factory, one instance per
        network (official ``encoder_modules[config['encoder']]()`` per network)."""
        agent = cls(config=official_config(**{k: v for k, v in config.items() if k != "agent_name"}),
                     obs_dim=int(obs_dim), action_dim=int(action_dim), device=torch.device(device))
        torch.manual_seed(int(seed))
        cfg = agent.config
        agent.critic = Value(obs_dim + action_dim, cfg["value_hidden_dims"], layer_norm=cfg["layer_norm"],
                             num_ensembles=2, encoder=encoder() if encoder else None)
        agent.actor_bc_flow = ActorVectorField(obs_dim + action_dim + 1, cfg["actor_hidden_dims"], action_dim,
                                               layer_norm=cfg["actor_layer_norm"],
                                               encoder=encoder() if encoder else None)
        agent.actor_onestep_flow = ActorVectorField(obs_dim + action_dim, cfg["actor_hidden_dims"], action_dim,
                                                    layer_norm=cfg["actor_layer_norm"],
                                                    encoder=encoder() if encoder else None)
        agent.target_critic = copy.deepcopy(agent.critic)  # params['modules_target_critic'] = params['modules_critic']
        for m in agent.modules().values():
            m.to(agent.device)
        agent.target_critic.requires_grad_(False)
        agent.optimizer = torch.optim.Adam(agent.online_parameters(), lr=cfg["lr"], betas=(0.9, 0.999), eps=1e-8)
        agent.generator = torch.Generator().manual_seed(int(seed))
        return agent

    # ------------------------------------------------------------------------------------------------ bookkeeping
    def modules(self) -> dict[str, nn.Module]:
        return {"critic": self.critic, "target_critic": self.target_critic, "actor_bc_flow": self.actor_bc_flow,
                "actor_onestep_flow": self.actor_onestep_flow}

    def online_parameters(self) -> list[nn.Parameter]:
        return [p for name in ("critic", "actor_bc_flow", "actor_onestep_flow")
                for p in getattr(self, name).parameters()]

    def state_dict(self) -> dict:
        return {"modules": {k: m.state_dict() for k, m in self.modules().items()},
                "optimizer": self.optimizer.state_dict(), "generator": self.generator.get_state(),
                "config": dict(self.config), "obs_dim": self.obs_dim, "action_dim": self.action_dim}

    def load_state_dict(self, state: dict) -> None:
        if (state["obs_dim"], state["action_dim"]) != (self.obs_dim, self.action_dim):
            raise ValueError("checkpoint dimensions differ from this agent")
        for k, m in self.modules().items():
            m.load_state_dict(state["modules"][k])
        self.optimizer.load_state_dict(state["optimizer"])
        self.generator.set_state(state["generator"])

    def train_mode(self, flag: bool) -> None:
        for m in self.modules().values():
            m.train(flag)

    @staticmethod
    def _frozen(module: nn.Module, *args, **kwargs):
        """Call ``module`` with its parameters detached (official: network.select(name)(...) without ``params``)."""
        params = {k: v.detach() for k, v in module.named_parameters()}
        buffers = dict(module.named_buffers())
        return functional_call(module, {**params, **buffers}, args, kwargs)

    # ------------------------------------------------------------------------------------------------ policy
    @torch.no_grad()
    def compute_flow_actions(self, observations, noises: torch.Tensor) -> torch.Tensor:
        """Euler integration of the BC flow (official ``compute_flow_actions``: encode once, ``flow_steps`` steps at
        t = i / flow_steps), clipped to [-1, 1]. Always stop-gradient, as in the official actor loss."""
        enc = self.actor_bc_flow.encode(observations)
        actions = noises
        steps = int(self.config["flow_steps"])
        for i in range(steps):
            t = torch.full((*enc.shape[:-1], 1), i / steps, dtype=actions.dtype, device=actions.device)
            vels = self.actor_bc_flow(enc, actions, t, is_encoded=True)
            actions = actions + vels / steps
        return actions.clamp(-1, 1)

    def sample_actions(self, observations, noises: torch.Tensor | None = None) -> torch.Tensor:
        """One-step policy (official ``sample_actions``), clipped to [-1, 1]; no gradients."""
        with torch.no_grad():
            if noises is None:
                lead = (observations if isinstance(observations, torch.Tensor)
                        else next(iter(observations.values()))).shape[0]
                noises = torch.randn(lead, self.action_dim, generator=self.generator)
            noises = noises.to(self.device)
            return self.actor_onestep_flow(observations, noises).clamp(-1, 1)

    # ------------------------------------------------------------------------------------------------ losses
    def critic_loss(self, batch: dict, noise: Noise) -> tuple[torch.Tensor, dict]:
        with torch.no_grad():
            next_actions = self.actor_onestep_flow(batch["next_observations"], noise.next_actions).clamp(-1, 1)
            next_qs = self.target_critic(batch["next_observations"], next_actions)
            next_q = next_qs.min(0).values if self.config["q_agg"] == "min" else next_qs.mean(0)
            target_q = batch["rewards"] + self.config["discount"] * batch["masks"] * next_q
        q = self.critic(batch["observations"], batch["actions"])
        loss = ((q - target_q) ** 2).mean()
        return loss, {"critic_loss": loss.detach(), "q_mean": q.mean().detach(), "q_max": q.max().detach(),
                      "q_min": q.min().detach()}

    def actor_loss(self, batch: dict, noise: Noise) -> tuple[torch.Tensor, dict]:
        x_1 = batch["actions"]
        x_0, t = noise.x0, noise.t
        x_t = (1 - t) * x_0 + t * x_1
        vel = x_1 - x_0
        pred = self.actor_bc_flow(batch["observations"], x_t, t)
        bc_flow_loss = ((pred - vel) ** 2).mean()

        target_flow_actions = self.compute_flow_actions(batch["observations"], noise.distill)
        actor_actions = self.actor_onestep_flow(batch["observations"], noise.distill)
        distill_loss = ((actor_actions - target_flow_actions) ** 2).mean()

        actor_actions = actor_actions.clamp(-1, 1)
        qs = self._frozen(self.critic, batch["observations"], actor_actions)
        q = qs.mean(0)
        q_loss = -q.mean()
        if self.config["normalize_q_loss"]:
            lam = (1.0 / q.abs().mean()).detach()
            q_loss = lam * q_loss
        loss = bc_flow_loss + self.config["alpha"] * distill_loss + q_loss

        with torch.no_grad():
            actions = self.actor_onestep_flow(batch["observations"], noise.mse).clamp(-1, 1)
            mse = ((actions - batch["actions"]) ** 2).mean()
        return loss, {"actor_loss": loss.detach(), "bc_flow_loss": bc_flow_loss.detach(),
                      "distill_loss": distill_loss.detach(), "q_loss": q_loss.detach(), "q": q.mean().detach(),
                      "mse": mse}

    def total_loss(self, batch: dict, noise: Noise) -> tuple[torch.Tensor, dict]:
        critic_loss, critic_info = self.critic_loss(batch, noise)
        actor_loss, actor_info = self.actor_loss(batch, noise)
        info = {f"critic/{k}": v for k, v in critic_info.items()}
        info.update({f"actor/{k}": v for k, v in actor_info.items()})
        return critic_loss + actor_loss, info

    def draw_noise(self, batch: dict) -> Noise:
        n = batch["actions"].shape[0]
        return Noise.draw(n, self.action_dim, self.generator, self.device)

    def update(self, batch: dict, noise: Noise | None = None) -> dict:
        """One official ``update``: Adam step on critic + actor loss, then the target update from the pre-update critic."""
        noise = noise if noise is not None else self.draw_noise(batch)
        old_critic = [p.detach().clone() for p in self.critic.parameters()]
        loss, info = self.total_loss(batch, noise)
        self.optimizer.zero_grad(set_to_none=True)
        loss.backward()
        info.update(self.grad_stats())
        self.optimizer.step()
        tau = float(self.config["tau"])
        with torch.no_grad():
            for tp, p_old in zip(self.target_critic.parameters(), old_critic):
                tp.copy_(p_old * tau + tp * (1 - tau))
        return {k: float(v) for k, v in info.items()}

    @torch.no_grad()
    def grad_stats(self) -> dict:
        """Official ``apply_loss_fn`` statistics over the parameter tree: max / min of all gradient entries and the sum
        of per-leaf L2 norms. A flax leaf of the critic ensemble holds both members; the target critic's leaves have
        zero gradient (included as zeros, as in the official tree); encoder parameters count one leaf each."""
        leaves: dict[str, list[torch.Tensor]] = {}
        seen = set()
        for key, tensor, _member, _kind in _official_slots(self):
            if key.startswith("modules_target_critic"):
                leaves.setdefault(key, []).append(torch.zeros(1))
                continue
            g = tensor.grad if tensor.grad is not None else torch.zeros_like(tensor)
            leaves.setdefault(key, []).append(g.detach().reshape(-1).cpu())
            seen.add(id(tensor))
        for i, p in enumerate(self.online_parameters()):
            if id(p) not in seen:  # encoder parameters (no official counterpart)
                g = p.grad if p.grad is not None else torch.zeros_like(p)
                leaves[f"encoder/{i}"] = [g.detach().reshape(-1).cpu()]
        flat = [torch.cat(v) for v in leaves.values()]
        return {"grad/max": torch.stack([f.max() for f in flat]).max(),
                "grad/min": torch.stack([f.min() for f in flat]).min(),
                "grad/norm": torch.stack([f.norm() for f in flat]).sum()}

    @torch.no_grad()
    def evaluate_losses(self, batch: dict, noise: Noise | None = None) -> dict:
        """Official validation metrics (``total_loss`` with ``grad_params=None``): losses only, no update."""
        noise = noise if noise is not None else self.draw_noise(batch)
        _, info = self.total_loss(batch, noise)
        return {k: float(v) for k, v in info.items()}


# ---------------------------------------------------------------------------------------------- official parameters
_OFFICIAL_MODULES = {"critic": "modules_critic/value_net", "target_critic": "modules_target_critic/value_net",
                     "actor_bc_flow": "modules_actor_bc_flow/mlp", "actor_onestep_flow": "modules_actor_onestep_flow/mlp"}
# official parameter prefix of each network's encoder (agents/fql.py :196-232: the BC-flow encoder is registered once,
# as ``actor_bc_flow_encoder``, and shared with ``actor_bc_flow``)
_OFFICIAL_ENCODERS = {"critic": "modules_critic/encoder", "target_critic": "modules_target_critic/encoder",
                      "actor_bc_flow": "modules_actor_bc_flow_encoder",
                      "actor_onestep_flow": "modules_actor_onestep_flow/encoder"}


def _official_slots(agent: FQLAgent):
    """(official flat name, torch tensor, ensemble member or None, kind) for every official parameter (encoders
    with an ``official_slots`` layout, e.g. ``s4d.rwlearn.pixel.ImpalaEncoder``, included)."""
    for name, prefix in _OFFICIAL_ENCODERS.items():
        enc = getattr(getattr(agent, name), "encoder", None)
        if enc is not None and hasattr(enc, "official_slots"):
            for key, tensor, kind in enc.official_slots(prefix):
                yield key, tensor, None, kind
    for name, prefix in _OFFICIAL_MODULES.items():
        module = getattr(agent, name)
        if isinstance(module, Value):
            for e, member in enumerate(module.members):
                for i, lin in enumerate(member.linears):
                    yield f"{prefix}/Dense_{i}/kernel", lin.weight, e, "kernel"
                    yield f"{prefix}/Dense_{i}/bias", lin.bias, e, "vector"
                for i, norm in enumerate(member.norms):
                    if isinstance(norm, nn.LayerNorm):
                        yield f"{prefix}/LayerNorm_{i}/scale", norm.weight, e, "vector"
                        yield f"{prefix}/LayerNorm_{i}/bias", norm.bias, e, "vector"
        else:
            for i, lin in enumerate(module.mlp.linears):
                yield f"{prefix}/Dense_{i}/kernel", lin.weight, None, "kernel"
                yield f"{prefix}/Dense_{i}/bias", lin.bias, None, "vector"
            for i, norm in enumerate(module.mlp.norms):
                if isinstance(norm, nn.LayerNorm):
                    yield f"{prefix}/LayerNorm_{i}/scale", norm.weight, None, "vector"
                    yield f"{prefix}/LayerNorm_{i}/bias", norm.bias, None, "vector"


@torch.no_grad()
def load_official_params(agent: FQLAgent, flat: dict) -> None:
    """Copy a flattened official parameter tree (``'modules_critic/value_net/Dense_0/kernel' -> array``; ensemble axis
    first, flax kernels (in, out)) into the agent. Every official name must be consumed exactly once."""
    used = set()
    for key, tensor, member, kind in _official_slots(agent):
        arr = torch.as_tensor(flat[key])
        arr = arr[member] if member is not None else arr
        tensor.copy_(arr.T if kind == "kernel" else arr.permute(3, 2, 0, 1) if kind == "conv_kernel" else arr)
        used.add(key)
    extra = set(flat) - used
    if extra:
        raise KeyError(f"official parameters without a torch slot: {sorted(extra)[:5]}")


@torch.no_grad()
def export_official_params(agent: FQLAgent) -> dict:
    """Inverse of ``load_official_params`` (numpy arrays in the official layout)."""
    out: dict[str, list] = {}
    for key, tensor, member, kind in _official_slots(agent):
        arr = (tensor.T if kind == "kernel" else tensor.permute(2, 3, 1, 0) if kind == "conv_kernel"
               else tensor).detach().cpu().numpy()
        if member is None:
            out[key] = arr
        else:
            out.setdefault(key, []).append(arr)
    import numpy as np

    return {k: (np.stack(v) if isinstance(v, list) else v) for k, v in out.items()}
